export function getCategoryPackages(slug) {
  return CATEGORY_PACKAGES[slug] ?? null;
}

export function getAllCategoryPackages() {
  return Object.entries(CATEGORY_PACKAGES).flatMap(([slug, packages]) =>
    packages.map((item) => ({ ...item, categorySlug: slug })),
  );
}
