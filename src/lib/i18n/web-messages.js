export function getWebMessages(code) {
  return WEB_MESSAGES[code] || WEB_MESSAGES.en;
}

export function formatMessage(template, vars = {}) {
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value ?? "")),
    template,
  );
}
